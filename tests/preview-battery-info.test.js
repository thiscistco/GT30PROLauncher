const grid=html.match(/<div class="battery-info-grid">([\s\S]*?)\n                <\/div>/)[1];
const cells=[...grid.matchAll(/<div class="battery-info-cell"(?: aria-hidden="true")?>([\s\S]*?)<\/div>/g)].map(m => (m[1].match(/<span class="battery-info-name">([^<]+)<\/span>/)||[])[1] || '');
