#!/usr/bin/env python3
"""Generate matching dot-matrix notes icons for Android and the browser preview."""
from pathlib import Path
patterns={
 'notes': ['.######..','.##....#.','.##....#.','.##.###..','.##......','.##.###..','.##......','.######..','.........'],
 'archive':['#########','#########','.##...##.','.##.###..','.##......','.##......','.##......','.#######.','.........'],
 'trash':['..#####..','#########','...###...','..##.##..','..##.##..','..##.##..','..##.##..','..#####..','.........'],
 'list':['##.######','##.######','.........','##.######','##.######','.........','##.######','##.######','.........'],
 'grid':['###..###.','###..###.','###..###.','.........','###..###.','###..###.','###..###.','.........','.........'],
 'staggered':['###..###.','###..###.','###..###.','###......','.....###.','###..###.','###..###.','.....###.','.........'],
 'tag':['#####....','##..##...','##...##..','##....##.','.##....##','..##..##.','...####..','.........','.........'],
 'checklist':['##...####','##...####','.........','##...####','##...####','.........','##...####','##...####','.........'],
 'done':['.......##','......##.','.....##..','##..##...','.####....','..##.....','.........','.........','.........'],
 'backup':['...###...','..##.##..','.##...##.','##.....##','...###...','....#....','....#....','#########','.........'],
 'pin':['..#####..','...###...','...###...','..#####..','.##...##.','#########','....#....','....#....','.........'],
 'unpin':['#...###..','##.###...','.####....','..####...','.##.###..','####.####','....#.##.','....#..##','.........'],
 'restore':['...####..','..##..##.','###....##','####.....','##.##....','....##.##','.....###.','.........','.........'],
 'color':['..#####..','.##...##.','##.#.#.##','##.....##','##.#.#.##','.##...##.','..##.##..','...###...','.........']}
root=Path(__file__).resolve().parents[1]
for name,pattern in patterns.items():
 assert len(pattern)==9 and all(len(row)==9 for row in pattern)
 coords=[(x+2,y+2) for y,row in enumerate(pattern) for x,v in enumerate(row) if v=='#']
 svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 13 13" fill="white">\n'+''.join('  <circle cx="%s" cy="%s" r=".39" />\n'%(x,y) for x,y in coords)+'</svg>\n'
 path=' '.join('M%s,%s a.39,.39 0 1,0 .78,0 a.39,.39 0 1,0 -.78,0 z'%(x-.39,y) for x,y in coords)
 xml='<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="13" android:viewportHeight="13">\n    <path android:fillColor="#FFFFFF" android:pathData="%s" />\n</vector>\n'%path
 (root/'preview/assets'/('notes-'+name+'.svg')).write_text(svg)
 (root/'app/src/main/res/drawable'/('ic_notes_'+name+'.xml')).write_text(xml)
